export function routeToSettings(
  tab?: SettingsTab,
  options?: { integration?: string }
): string {
  const qs = new URLSearchParams();
  if (tab && tab !== "integrations") {
    qs.set("tab", tab);
  }
  if (options?.integration) {
    qs.set("integration", options.integration);
  }
  const s = qs.toString();
  return s ? `/settings?${s}` : "/settings";
}

/** Deep-link to Integrations with a specific connector detail open. */
export function routeToIntegrationSettings(integrationId: string): string {
  return `/settings?integration=${encodeURIComponent(integrationId)}`;
}

/**
 * Adds a return target to a detail URL so downstream pages can provide
 * context-aware "Back to ..." behavior instead of always falling back to a
 * canonical list page.
 */
export function appendReturnTo(href: string, returnTo?: string | null): string {
  if (!returnTo) return href;
  const [path, qs = ""] = href.split("?");
  const params = new URLSearchParams(qs);
  params.set("returnTo", returnTo);
  const nextQs = params.toString();
  return nextQs ? `${path}?${nextQs}` : path;
}

export function safeReturnTo(
  returnTo: string | null | undefined,
  fallback: string
): string {
  if (!returnTo) return fallback;
  // Only allow in-app absolute paths.
  if (!returnTo.startsWith("/")) return fallback;
  return returnTo;
}

